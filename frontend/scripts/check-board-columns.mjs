import assert from 'node:assert/strict';
import { boardColumns, destinationColumns } from '../src/lib/board-columns.ts';
const dev = { id: 10, project: 1, kind: 'in_progress', name: 'In Dev', order: 1 };
const testing = { ...dev, id: 11, name: 'Testing', order: 2 };
const review = { ...dev, id: 12, name: 'QA', kind: 'review', order: 3 };
const other = { ...dev, id: 13, name: 'Blocked', kind: 'other', order: 4 };
const projects = [{ id: 1, columns: [testing, dev, review, other] }];
const task = { project: 1, column: review };
const stage = { id: -3, kind: 'in_progress', name: 'In Progress' };
assert.deepEqual(destinationColumns(task, stage, projects), [dev, testing]);
assert.deepEqual(destinationColumns({ ...task, column: testing }, stage, projects), [testing]);
assert.deepEqual(destinationColumns(task, { id: -4, kind: 'review' }, projects), [review]);
assert.deepEqual(destinationColumns(task, { id: -6, kind: 'other' }, projects), [other]);
assert.deepEqual(destinationColumns(task, { id: -5, kind: 'done' }, projects), []);
assert.deepEqual(destinationColumns(task, testing, projects), [testing]);
assert.deepEqual(destinationColumns(task, { ...dev, id: 99, project: 2 }, projects), []);
assert.deepEqual(boardColumns(projects[0]).map(c => c.name), ['In Dev', 'Testing', 'QA', 'Blocked']);
assert.deepEqual(boardColumns(projects[0], 'testing').map(c => c.id), [11]);
assert.deepEqual(boardColumns().map(c => c.kind), ['backlog', 'todo', 'in_progress', 'review', 'done', 'other']);
assert.ok(boardColumns().every(c => c.id < 0));
assert.equal(boardColumns(projects[0], 'missing').length, 0);
console.log('Board columns and destination checks passed');
